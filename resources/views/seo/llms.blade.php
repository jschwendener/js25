# Jonas Schwendener

> Jonas Schwendener designs and develops software for the modern web. Co-founder and lead developer of Blond, the Swiss operating system for small businesses.

## About

- Co-founder and lead developer of [Blond](https://blond.swiss) (StrawBlond GmbH, Switzerland). Blond brings quotes, invoices, time tracking, bookkeeping and banking together in one place, and an AI agent takes care of the busywork.
- Previously worked at [Racerfish](https://racerfish.com), a full-service digital agency, on Nitrous Evolve, the agency's in-house CMS, and on the many websites and web apps built with it.

